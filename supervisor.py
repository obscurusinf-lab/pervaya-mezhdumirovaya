def check(path):
    txt = io.open(path, encoding='utf-8').read()
    lines = txt.split('\n')
    m = re.search(r'glava-(\d+)', os.path.basename(path))
    num = int(m.group(1)) if m else 0
    far = num in FAR_SIDE_CHAPTERS
    human_only = num in HUMAN_CHAPTERS
    sides = mark_sides(lines, default='far' if far else 'human')
    issues = []

    for i, line in enumerate(lines, 1):
        low = line.lower()

        for pat, msg in TYPO:
            if re.search(pat, line):
                issues.append(('типографика', i, msg, line[:100]))

        for pat, msg in STYLE_BANS:
            if re.search(pat, low):
                issues.append(('стиль', i, msg, line[:100]))

        for pat, msg in CHEW:
            if re.search(pat, line):
                issues.append(('разжёвывание', i, msg, line[:100]))

        for pat, msg in REPEATS:
            if re.search(pat, line):
                issues.append(('повтор приёма', i, msg, line[:100]))

        for bad, good in NAME_TRAPS.items():
            if bad in line:
                issues.append(('имя', i, f'«{bad}» → «{good}»', line[:100]))

        far_context = sides[i - 1] == 'far'

        if far or (num in MIXED_CHAPTERS and far_context):
            for w in MODERN_WORDS:
                if re.search(w, low) and not any(ok in low for ok in FAR_SIDE_OK):
                    issues.append(('словарь той стороны', i, f'современное слово рядом с «{w.strip()}»', line[:100]))

        if human_only or (num in MIXED_CHAPTERS and not far_context):
            for w in FAR_WORDS_IN_HUMAN:
                if w.lower() in low and not any(ff in low for ff in HUMAN_FALSE_FRIENDS):
                    issues.append(('словарь людей', i, f'слово той стороны «{w}»', line[:100]))
            for pat in SVET_LEAK_PATTERNS:
                if re.search(pat, low):
                    issues.append(('словарь людей', i,
                                   '«свет» — их слово для ядерного удара; у людей изделие/спецбоеприпас/«Кассандра»',
                                   line[:100]))

        # утечка знания: имя той стороны в главе, целиком объявленной
        # человеческой (в MIXED_CHAPTERS не проверяем — там само наличие
        # имени и есть сигнал, что строка принадлежит той стороне,
        # проверить это здесь нечем, см. КАНОН.md)
        if human_only:
            for name in FAR_SIDE_NAMES:
                if re.search(r'\b' + name + r'\b', line):
                    issues.append(('утечка знания', i,
                                   f'имя той стороны «{name}» в человеческой главе — люди не могут его знать',
                                   line[:100]))

        # голое «изделие» у той стороны начиная с главы 8
        if num >= IZDELIE_FROM_CHAPTER and (far or far_context) and 'издели' in low:
            if not any(ok in low for ok in IZDELIE_OK):
                issues.append(('изделие', i,
                               'какое именно? свет или малое — уточнить, читатель не различит',
                               line[:100]))

        # смешанные главы: часы и минуты во «вставках от той стороны»
        if num in MIXED_CHAPTERS and far_context:
            for pat in CLOCK_UNITS:
                if re.search(pat, low):
                    issues.append(('часы у той стороны', i,
                                   'в абзаце с их лексикой считают по часам — перевести на солнце или вдохи',
                                   line[:100]))
                    break

        # нанизанные деепричастия: три и более подряд в одном предложении
        ger = re.findall(r'\b\w+(?:ая|яя|ав|ив|вшись|ясь|аясь)\b\s*,', line)
        if len(ger) >= 3:
            issues.append(('стиль', i, 'подряд три и более деепричастных оборота', line[:100]))

    issues.extend(check_dialogue(lines))

    for name, (pat, allowed) in CANON_FACTS.items():
        for mm in re.finditer(pat, txt, flags=re.IGNORECASE):
            val = mm.group(1).lower()
            if val not in [a.lower() for a in allowed]:
                line_no = txt[:mm.start()].count('\n') + 1
                issues.append(('канон', line_no, f'{name}: «{val}», по канону {allowed[0]}', mm.group(0)[:80]))

    return issues


def mark_sides(lines, default='human'):
    """Кому принадлежит каждая строка — людям или той стороне.

    Стороны в смешанных главах идут длинными блоками, поэтому сторона
    «липкая»: один раз опознали по имени или по лексике и держим до
    следующего опознанного маркера. Окно в пару абзацев тут не годится —
    внутри блока попадаются абзацы без единого имени.
    """
    sides = []
    cur = default
    for line in lines:
        low = line.lower()
        if any(m in low for m in FAR_SIDE_MARKERS):
            cur = 'far'
        elif any(m in low for m in HUMAN_MARKERS):
            cur = 'human'
        sides.append(cur)
    return sides


def check_dialogue(lines):
    """Замечание заказчика после гл. 11: диалоги тяжело читаются.

    Ловится механическая часть: однообразная архитектура реплик, отсутствие
    атрибуции при трёх и более говорящих, реплики-простыни и списки внутри
    реплики. Остальное — вслух, глазами.
    """
    issues = []

    # реплики подряд, с исходными номерами строк
    replies = [(i, l) for i, l in enumerate(lines, 1) if l.startswith('— ')]
    if not replies:
        return issues

    # разбить на серии: соседние реплики, между которыми нет прозы
    runs, run = [], []
    prev_idx = None
    for i, l in replies:
        between = lines[prev_idx:i - 1] if prev_idx is not None else []
        broken = any(s.strip() and not s.startswith('— ') for s in between)
        if prev_idx is not None and not broken:
            run.append((i, l))
        else:
            if len(run) > 1:
                runs.append(run)
            run = [(i, l)]
        prev_idx = i
    if len(run) > 1:
        runs.append(run)

    for run in runs:
        # длинная серия подряд, и ни одна реплика не подписана.
        # порог 5: чистая перекличка двоих читается и без подписей,
        # проблема начинается там, где говорящих больше и счёт сбивается
        unattributed = [(i, l) for i, l in run if not is_attributed(l)]
        if len(run) >= 5 and len(unattributed) == len(run):
            i, l = run[0]
            issues.append(('диалог', i,
                           f'{len(run)} реплик подряд без атрибуции — подписать хотя бы первую каждого говорящего',
                           l[:100]))

        # однообразная архитектура: «— реплика. — Действие. — продолжение»
        # три такие в окне из четырёх подряд идущих реплик
        flags = [l.count('—') >= 3 for _, l in run]
        for k in range(len(flags) - 3):
            if sum(flags[k:k + 4]) >= 3:
                i, l = run[k]
                issues.append(('диалог', i,
                               'три реплики со вставленной ремаркой подряд — развести действие в отдельный абзац',
                               l[:100]))
                break

    for i, l in replies:
        speech = spoken_part(l)
        if len(speech) > 400:
            issues.append(('диалог', i, f'реплика-простыня ({len(speech)} знаков речи) — разбить', l[:100]))
        # именно перечисление, а не «что» как союз: три и более «, что» подряд
        if len(re.findall(r',\s*что\b', speech)) >= 3:
            issues.append(('диалог', i,
                           'список «, что…, что…, что…» внутри реплики — разбить на отдельные предложения',
                           l[:100]))

    return issues


def spoken_part(line):
    """Из «— Речь. — Ремарка. — Речь.» вернуть только речь.

    Ремарка в русской типографике стоит между тире чётными кусками,
    поэтому берём куски с чётными индексами.
    """
    body = line[2:] if line.startswith('— ') else line
    chunks = body.split(' — ')
    return ' '.join(chunks[::2])


SPEECH_VERBS = (
    'сказал', 'спросил', 'ответил', 'произн', 'повторил', 'подтвердил',
    'согласил', 'добавил', 'заметил', 'отозвал', 'возразил', 'перебил',
    'уточнил', 'поправил',
)


def is_attributed(line):
    low = line.lower()
    if any(v in low for v in SPEECH_VERBS):
        return True
    return any(n in line for n in NAMES)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('-')]
    flags = {a for a in sys.argv[1:] if a.startswith('-')}
    brief = bool(flags & {'-b', '--brief'})

    files = args or sorted(glob.glob('pervaya-mezhdumirovaya-glava-*.md'))
    if not files:
        print('Не найдено файлов глав (pervaya-mezhdumirovaya-glava-*.md) и аргументы не переданы.')
        return

    total = 0
    for f in files:
        iss = check(f)
        total += len(iss)
        if brief and not iss:
            continue
        print(f'\n=== {os.path.basename(f)} — замечаний: {len(iss)}')
        for kind, line, msg, ctx in iss:
            print(f'  [{kind}] стр.{line}: {msg}')
            if not brief:
                print(f'      {ctx}')

    print(f'\nИтого замечаний: {total}')
    if not brief:
        print('Проверено автоматикой. Сюжетные связи, мотивация и знание персонажей — вручную, по КАНОН.md.')


if __name__ == '__main__':
    main()
