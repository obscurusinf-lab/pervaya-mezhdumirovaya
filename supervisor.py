# --- канон: имена -------------------------------------------------------------
NAMES = {
    'Ханнар', 'Илех', 'Совиль', 'Оуна', 'Тэй', 'Аллех', 'Ирша', 'Тэммет',
    'Марта', 'Клейн', 'Ковач', 'Тахира', 'Бенали', 'Мбайе', 'Ибрагим', 'Дауд',
    'Дюпон', 'Ленуар', 'Нгарта', 'Аллахи', 'Абакар',
}

# частые опечатки/варианты, которых быть не должно (неверное -> верное)
NAME_TRAPS = {
    'Ханар': 'Ханнар', 'Ханнер': 'Ханнар',
    'Иллех': 'Илех',
    'Совилль': 'Совиль', 'Совилъ': 'Совиль',
    'Оунна': 'Оуна',
    'Мбае': 'Мбайе', 'Мбайэ': 'Мбайе', 'Мбайи': 'Мбайе',
    'Ибраим': 'Ибрагим',
    'Ковацу': 'Ковач', 'Ковачу': 'Ковач',  # проверяется отдельно как дательный падеж, см. ниже
    'Тагира': 'Тахира',
    'Клеин': 'Клейн', 'Кляйн': 'Клейн',
    'Дюпонт': 'Дюпон',
    'Абаккар': 'Абакар', 'Абаккер': 'Абакар',
}
# дательный падеж "Ковачу" — валидная форма, исключаем из ловушек
NAME_TRAPS.pop('Ковачу', None)

# --- главы «той стороны»: их вставки допустимы также в 9-10 (смешанные) -------
FAR_SIDE_CHAPTERS = {3, 5, 8}
HUMAN_CHAPTERS = {1, 2, 4, 6, 7, 11}
MIXED_CHAPTERS = {9, 10}

# лексика той стороны, которой не место в чисто человеческих главах
FAR_WORDS_IN_HUMAN = [
    'створ', 'поголовь', 'разбор', 'сложени', 'полог', 'накопител',
    'ветвь', 'доля мастера', 'след руки', 'читающ', 'одарённ', 'одаренн',
]
# слова, у которых есть невинное человеческое значение — не флагать при их наличии в строке
HUMAN_FALSE_FRIENDS = ['разборчив', 'расход', 'разбор полёт', 'разбор происшеств']

# современная военная лексика, недопустимая у той стороны (главы 3, 5, 8)
MODERN_WORDS = [
    'табельное', 'пистолет', 'автомат', r'\bкилометр', r'\bметр\w*\b',
    r'\bсекунд', r'\bминут', r'\bчас(ов|а)?\b',
    'офицер', 'сержант', 'капитан', 'генерал', 'рота', 'батальон', 'дивизи', 'штаб',
    'радар', 'спутник', 'рация', 'связь по', 'бинокль', 'процент', 'ракет', 'бомб',
    'артиллер', 'боеприпас', 'патрон', 'танк', 'самолёт', 'самолет', 'вертолёт', 'вертолет',
    'двигател', 'гусениц', 'позици', 'заряд', 'подрыв', 'окоп', 'блиндаж', 'техник',
]
# слова, допустимые у них (их собственные единицы измерения и понятия — не современная лексика)
FAR_SIDE_OK = [
    'шаг', 'луна', 'покой', 'створ', 'полог', 'сложение', 'накопител', 'разбор', 'поголовь',
]

# --- стилевые запреты пользователя --------------------------------------------
STYLE_BANS = [
    (r'это не просто .{0,40}, это', 'конструкция «это не просто А, это Б»'),
    (r'не про .{0,30}, а про', 'конструкция «не про А, а про Б»'),
    (r'дело не в .{0,30}, а в', 'конструкция «дело не в А, а в Б»'),
    (r'когда происходит .{0,30}, это приводит', 'конструкция «когда происходит А, это приводит к Б»'),
    (r'не только .{0,60}, но и', '«не только, но и» — проверить реальное противопоставление'),
]

# --- повторяющиеся ударные фигуры — следить, чтобы не размножались -----------
REPEATS = [
    (r'[Ээ]то (была|был|было) не [^.!?\n]{1,40}[.!?]\s*[Ээ]то (была|был|было)',
     'двухтактная концовка «это было не А. Это было Б» — уже использована в гл. 4 («мы воевали со сметой»), второй раз не ставить'),
    (r'[Мм]ы воевали не с [^.!?\n]{1,30}[.!?]\s*[Мм]ы воевали',
     'та же фигура через «мы воевали»'),
]

# --- разжёвывание --------------------------------------------------------------
CHEW = [
    (r'—\s*(То есть|Иными словами|Другими словами)\b', 'пересказ только что сказанного'),
    (r'\bи в этом (всё дело|вся суть)\b', 'нажим на вывод'),
    (r'потому что это (была|был|было) сам(ая|ый|ое)\b', 'подсказка читателю о важности'),
    (r'\bПозже,? .{0,40}он[а]? пойм[её]т\b', 'авторское пояснение приёма заранее'),
]

# --- типографика ----------------------------------------------------------------
TYPO = [
    (r'  ', 'двойной пробел'),
    (r' [,.;:!?]', 'пробел перед знаком препинания'),
    (r'"', 'прямые кавычки вместо « »'),
    (r'^- ', 'дефис вместо тире в начале реплики'),
    (r'\.\.\.', 'три точки вместо символа многоточия «…»'),
    (r'\bеще\b', '«еще» без ё (проверить: «ещё»)'),
    (r'\bвсе\s+(же|таки)\b', 'проверить ё во «всё же/всё-таки»'),
]

# --- канонические числа (см. КАНОН.md) -----------------------------------------
CANON_FACTS = {
    'мощность «Кассандры»':
        (r'(\d+|пятнадцать)\s*килотонн', ['пятнадцать', '15']),
    'высота подрыва «Кассандры»':
        (r'подрыв\w*[^.]{0,30}?(\d+|четыреста)\s*метр', ['четыреста', '400']),
    'дистанция Ханнара от эпицентра':
        (r'в (\w+)\s*(?:шагах|метрах) от (?:середины|эпицентра)', ['шестистах', '600']),
    'размер фермы':
        (r'(\w+)\s*на восемь километров', ['двенадцать', '12']),
    'состав отряда «Талисман»':
        (r'отряд[а-я]*,?\s*(сто сорок|140)\s*человек', ['сто сорок', '140']),
    'квота на квартал':
        (r'на квартал (\w+)\s*применени', ['двенадцать', '12']),
    'предел Стоящих (метры)':
        (r'(\d{3,4})\s*метр\w*\s*(?:и\s*\d{3,4}\s*)?(?:по двум )?рак', ['4200', '4110']),
}


def check(path):
    txt = io.open(path, encoding='utf-8').read()
    lines = txt.split('\n')
    m = re.search(r'glava-(\d+)', os.path.basename(path))
    num = int(m.group(1)) if m else 0
    far = num in FAR_SIDE_CHAPTERS
    human_only = num in HUMAN_CHAPTERS
    issues = []

    for i, line in enumerate(lines, 1):
        low = line.lower()

        for pat, msg in TYPO:
            if re.search(pat, line):
                issues.append(('типографика', i, msg, line[:100]))

        for pat, msg in STYLE_BANS:
            if re.search(pat, low):
                issues.append(('стиль', i, msg, line[:100]))

        for pat, msg in CHEW:
            if re.search(pat, line):
                issues.append(('разжёвывание', i, msg, line[:100]))

        for pat, msg in REPEATS:
            if re.search(pat, line):
                issues.append(('повтор приёма', i, msg, line[:100]))

        for bad, good in NAME_TRAPS.items():
            if bad in line:
                issues.append(('имя', i, f'«{bad}» → «{good}»', line[:100]))

        if far:
            for w in MODERN_WORDS:
                if re.search(w, low) and not any(ok in low for ok in FAR_SIDE_OK):
                    issues.append(('словарь той стороны', i, f'современное слово рядом с «{w.strip()}»', line[:100]))

        if human_only:
            for w in FAR_WORDS_IN_HUMAN:
                if w.lower() in low and not any(ff in low for ff in HUMAN_FALSE_FRIENDS):
                    issues.append(('словарь людей', i, f'слово той стороны «{w}»', line[:100]))

        # нанизанные деепричастия: три и более подряд в одном предложении
        ger = re.findall(r'\b\w+(?:ая|яя|ав|ив|вшись|ясь|аясь)\b\s*,', line)
        if len(ger) >= 3:
            issues.append(('стиль', i, 'подряд три и более деепричастных оборота', line[:100]))

    for name, (pat, allowed) in CANON_FACTS.items():
        for mm in re.finditer(pat, txt, flags=re.IGNORECASE):
            val = mm.group(1).lower()
            if val not in [a.lower() for a in allowed]:
                line_no = txt[:mm.start()].count('\n') + 1
                issues.append(('канон', line_no, f'{name}: «{val}», по канону {allowed[0]}', mm.group(0)[:80]))

    return issues


def main():
    files = sys.argv[1:] or sorted(glob.glob('pervaya-mezhdumirovaya-glava-*.md'))
    if not files:
        print('Не найдено файлов глав (pervaya-mezhdumirovaya-glava-*.md) и аргументы не переданы.')
        return
    total = 0
    for f in files:
        iss = check(f)
        total += len(iss)
        print(f'\n=== {os.path.basename(f)} — замечаний: {len(iss)}')
        for kind, line, msg, ctx in iss:
            print(f'  [{kind}] стр.{line}: {msg}')
            print(f'      {ctx}')
    print(f'\nИтого замечаний: {total}')
    print('Проверено автоматикой. Сюжетные связи, мотивация и знание персонажей — вручную, по КАНОН.md.')


if __name__ == '__main__':
    main()
