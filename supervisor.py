"""
Скрипт-супервайзер для «Первой Междумировой».
Запуск: python3 supervisor.py [файлы глав ...]
Без аргументов проверяет все pervaya-mezhdumirovaya-glava-*.md в текущей папке.

Проверяет: типографику, стилевые запреты заказчика, разжёвывание,
повтор однажды использованных фигур речи, опечатки в именах,
смешение словарей двух сторон и канонические числа из КАНОН.md.

Сюжетные связи, мотивация и знание персонажей — вручную, по КАНОН.md.
"""
